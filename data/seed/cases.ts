export function getCaseById(id: string): Case | undefined {
  return SEED_CASES.find(c => c.id === id);
}

export function getCases(filter?: {
  status?: string;
  claimType?: string;
  autonomyTier?: string;
  limit?: number;
}): Case[] {
  let cases = [...SEED_CASES];
  if (filter?.status && filter.status !== 'all') {
    cases = cases.filter(c => c.status === filter.status);
  }
  if (filter?.claimType && filter.claimType !== 'all') {
    cases = cases.filter(c => c.claimType === filter.claimType);
  }
  if (filter?.autonomyTier && filter.autonomyTier !== 'all') {
    cases = cases.filter(c => c.autonomyTier === filter.autonomyTier);
  }
  if (filter?.limit) {
    cases = cases.slice(0, filter.limit);
  }
  return cases;
}
